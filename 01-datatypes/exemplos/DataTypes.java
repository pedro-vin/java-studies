public class DataTypes {

    public static void main(String[] args) {

        // Declara variável sem tipo

        var variavel = "valor"; // recebe o tipo conforme o valor

        // Tipos primitivos

        // números inteiros

        byte numero; // valores de -128 a 127 (8 bits na memória)

        short numero2; // valores de -32.768 a 32.767 (16 bits na memória)

        int inteiro; // valores de -2.147.483.648 a 2.147.483.647 (32 bits na memória)

        long numeroLongo; // valores de -9.223.372.036.854.775.808 a 9.223.372.036.854.755.807 (64 bits na memória)

        // números decimais

        float f; // 32 bits - precisão simples (poucos números após a vírgula)

        double d; // 64 bits - precisão dupla (muitos números após a vírgula)

        // texto

        String palavra; // armazenar palavras e frases - aspas duplas

        char caractere; // armazenar um único caractere - aspas simples

        // boolean

        boolean b; // valor true ou false
    }


}
